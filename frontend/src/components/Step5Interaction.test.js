import { describe, it, expect, vi, afterEach } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'

// Strangers chat with agents named after real people and organisations. The page must
// say, in chat and in survey mode, that these are simulated personas.

vi.mock('../api/report', () => ({
  chatWithReport: vi.fn(),
  getReport: vi.fn(async () => ({ success: false })),
  getAgentLog: vi.fn(),
}))
vi.mock('../api/simulation', () => ({
  interviewAgents: vi.fn(),
  getSimulationProfilesRealtime: vi.fn(async () => ({
    success: true,
    data: { profiles: [{ username: 'Ofgem', profession: 'Regulator' }] },
  })),
  getEnvStatus: vi.fn(async () => ({ success: false })),
}))
vi.mock('../demo/config', () => ({ isDemoMode: false }))

import Step5Interaction from './Step5Interaction.vue'

const NOTE = 'You are talking to simulated personas. Their answers are generated by the engine. '
  + 'They are not the real views of the people or organisations named.'

describe('Step5Interaction persona note', () => {
  afterEach(() => vi.clearAllMocks())

  it('shows the note in chat mode and in survey mode', async () => {
    const wrapper = mount(Step5Interaction, { props: { reportId: 'r1', simulationId: 's1' } })
    await flushPromises()

    expect(wrapper.find('.chat-container').exists()).toBe(true)
    expect(wrapper.find('[data-test="persona-note"]').text().replace(/\s+/g, ' ')).toBe(NOTE)

    await wrapper.find('.survey-pill').trigger('click')
    expect(wrapper.find('.survey-container').exists()).toBe(true)
    expect(wrapper.find('.chat-container').exists()).toBe(false)
    expect(wrapper.find('[data-test="persona-note"]').text().replace(/\s+/g, ' ')).toBe(NOTE)
    wrapper.unmount()
  })
})
