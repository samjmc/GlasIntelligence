_ROLE_TOOL_PROMPT = """\
You are assigning tool roles to agents in a social media simulation.

Simulation scenario: {simulation_requirement}

Available tool roles:
- "leader": Government officials, heads of state, corporate executives. Gets: scenario action tools + web search
- "diplomat": Diplomats, negotiators, mediators. Gets: scenario action tools + web search + news
- "analyst": Researchers, journalists, think tank members. Gets: web search + news + financial data
- "operative": Military, intelligence, field operatives. Gets: scenario action tools + web search
- "observer": Citizens, activists, commentators. Gets: web search only
- "none": Agents that should NOT have tools (purely social media participants)

For each agent below, assign exactly one role. Consider their entity type,
name, and stance.

Agents:
{agent_list}

Return a JSON object mapping agent_id (as string) to role.
Example: {{"0": "leader", "1": "analyst", "2": "observer"}}

Return ONLY the JSON object, no other text."""


def assign_tool_roles(
    agent_configs: list[dict[str, Any]],
    simulation_requirement: str,
) -> dict[int, str]:
    """Use LLM to assign tool roles to agents based on their entity type and stance."""
    if not Config.LLM_API_KEY or not agent_configs:
        return {}

    agent_lines = []
    for ac in agent_configs:
        agent_lines.append(
            f"- Agent {ac.get('agent_id', '?')}: "
            f"name={ac.get('entity_name', 'unknown')}, "
            f"type={ac.get('entity_type', 'unknown')}, "
            f"stance={ac.get('stance', 'neutral')}"
        )
    agent_list_str = "\n".join(agent_lines)

    prompt = _ROLE_TOOL_PROMPT.format(
        simulation_requirement=simulation_requirement,
        agent_list=agent_list_str,
    )

    try:
        client = OpenAI(api_key=Config.LLM_API_KEY, base_url=Config.LLM_BASE_URL)
        response = client.chat.completions.create(
            model=Config.LLM_MODEL_NAME,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.3,
            max_tokens=1000,
        )
        raw = response.choices[0].message.content.strip()

        json_match = re.search(r"\{.*\}", raw, re.DOTALL)
        if not json_match:
            logger.warning("LLM did not return valid JSON for tool role assignments")
            return {}

        role_map = json.loads(json_match.group())
        result = {}
        valid_roles = {"leader", "diplomat", "analyst", "operative", "observer", "none"}
        for agent_id_str, role in role_map.items():
            try:
                aid = int(agent_id_str)
                result[aid] = role if role in valid_roles else "observer"
            except ValueError:
                continue

        logger.info(f"Assigned tool roles: {result}")
        return result

    except Exception as e:
        logger.error(f"Failed to assign tool roles: {e}")
        return {}


