_SCENARIO_TOOL_PROMPT = """\
You are designing tools for AI agents in a social media simulation.

The simulation scenario is:
{simulation_requirement}

The agents represent these entity types: {entity_types}

Generate 3-5 scenario-specific action tools that agents could use beyond
social media posting. Each tool should:
- Be a meaningful action within the scenario (e.g. propose_sanction,
  form_alliance, issue_statement, deploy_resources, call_vote)
- Accept string arguments that describe the action
- Return a string description of what happened (this becomes visible on
  the social feed)
- Produce mechanical side effects on the simulation state

Return a JSON array of tool definitions. Each definition has:
- "name": snake_case function name (max 30 chars)
- "description": What the tool does and when to use it (2-3 sentences)
- "param_name": Name of the main string parameter
- "param_description": Description of what to pass
- "effects": Array of state effects this tool produces. Each effect has:
  - "effect_type": one of "suppress_agent", "boost_agent", "create_link", "break_link", "broadcast"
  - "target": "self" (affects the calling agent), "named" (target extracted from action_description), or "all"
  - "magnitude": 0.0-0.7 (how strong the effect is, e.g. 0.2=mild, 0.5=significant, 0.7=severe)
  - "direction": "actor_to_target" or "target_to_actor" or "bidirectional" (for link effects only)

Effect types explained:
- suppress_agent: Reduces target's activity_level (they post less frequently)
- boost_agent: Increases target's activity_level (they post more frequently)
- create_link: Creates a follow relationship between agents (they see each other's content)
- break_link: Removes a follow relationship (they stop seeing each other's content)
- broadcast: No state change, just a visible announcement in the feed

Example:
[
  {{
    "name": "propose_sanction",
    "description": "Propose economic sanctions against a nation or entity. Use when you want to take a formal economic action against another party.",
    "param_name": "proposal",
    "param_description": "Description of the sanctions: target, severity (limited/moderate/severe), and rationale",
    "effects": [
      {{"effect_type": "suppress_agent", "target": "named", "magnitude": 0.4}},
      {{"effect_type": "break_link", "target": "named", "direction": "bidirectional"}}
    ]
  }},
  {{
    "name": "form_alliance",
    "description": "Form a strategic alliance with another entity. Use when you want to strengthen ties and increase cooperation.",
    "param_name": "alliance_details",
    "param_description": "Description of the alliance: partner, terms, and strategic objectives",
    "effects": [
      {{"effect_type": "create_link", "target": "named", "direction": "bidirectional"}},
      {{"effect_type": "boost_agent", "target": "named", "magnitude": 0.2}}
    ]
  }}
]

Return ONLY the JSON array, no other text."""


@dataclass
class ScenarioToolDef:
    """Definition of a scenario-specific tool generated by LLM."""

    name: str
    description: str
    param_name: str
    param_description: str
    effects: list[dict] = None  # List of effect specs from LLM

    def __post_init__(self):
        if self.effects is None:
            self.effects = []


def generate_scenario_tool_definitions(
    simulation_requirement: str,
    entity_types: list[str],
) -> list[ScenarioToolDef]:
    """Use LLM to generate scenario-specific tool definitions."""
    if not Config.LLM_API_KEY:
        logger.warning("No LLM_API_KEY — skipping scenario tool generation")
        return []

    entity_str = ", ".join(entity_types[:10]) if entity_types else "various stakeholders"
    prompt = _SCENARIO_TOOL_PROMPT.format(
        simulation_requirement=simulation_requirement,
        entity_types=entity_str,
    )

    try:
        client = OpenAI(api_key=Config.LLM_API_KEY, base_url=Config.LLM_BASE_URL)
        response = client.chat.completions.create(
            model=Config.LLM_MODEL_NAME,
            messages=[{"role": "user", "content": prompt}],
            temperature=0.7,
            max_tokens=2500,
        )
        raw = response.choices[0].message.content.strip()

        json_match = re.search(r"\[.*\]", raw, re.DOTALL)
        if not json_match:
            logger.warning("LLM did not return valid JSON array for scenario tools")
            return []

        definitions = json.loads(json_match.group())
        valid_effect_types = {"suppress_agent", "boost_agent", "create_link", "break_link", "broadcast"}
        tools = []
        for d in definitions[:5]:
            name = re.sub(r"[^a-z0-9_]", "", d.get("name", "")[:30])
            if not name:
                continue
            raw_effects = d.get("effects", [])
            effects = []
            for eff in raw_effects or []:
                if eff.get("effect_type") in valid_effect_types:
                    effects.append(
                        {
                            "effect_type": eff["effect_type"],
                            "target": eff.get("target", "named"),
                            "magnitude": min(float(eff.get("magnitude", 0.4)), 0.7),
                            "direction": eff.get("direction", "actor_to_target"),
                        }
                    )
            tools.append(
                ScenarioToolDef(
                    name=name,
                    description=d.get("description", "Perform a scenario action."),
                    param_name=d.get("param_name", "action_description"),
                    param_description=d.get("param_description", "Description of the action to take"),
                    effects=effects,
                )
            )
        logger.info(f"Generated {len(tools)} scenario tools: {[t.name for t in tools]}")
        return tools

    except Exception as e:
        logger.error(f"Failed to generate scenario tools: {e}")
        return []


_effect_engine_ref = None


def set_effect_engine(engine):
    """Set the global effect engine reference for tool functions to queue effects."""
    global _effect_engine_ref
    _effect_engine_ref = engine


def _make_scenario_tool_function(tool_def: ScenarioToolDef):
    """Create a callable function from a ScenarioToolDef.

    Dynamically builds a function with proper signature, docstring, and
    type annotations so CAMEL's FunctionTool can introspect it.
    When the tool has effects, queues StateEffect instances on the global
    EffectEngine.
    """
    from .simulation_effects import EffectType, StateEffect

    effects_specs = tool_def.effects or []

    def tool_fn(action_description: str) -> str:
        result = f"[{tool_def.name.upper()}] {action_description}"
        _log_tool_call(tool_def.name, {"action_description": action_description}, result)

        engine = _effect_engine_ref
        if engine and effects_specs:
            actor_id = _current_agent_id.get()
            platform = _current_platform.get()
            for spec in effects_specs:
                target_name = ""
                target_id = None

                if spec.get("target") == "self":
                    target_id = actor_id
                elif spec.get("target") == "named":
                    target_name = action_description
                # "all" leaves target_id None, handled by BROADCAST

                try:
                    etype = EffectType(spec["effect_type"])
                except ValueError:
                    continue

                engine.queue(
                    StateEffect(
                        effect_type=etype,
                        actor_id=actor_id,
                        target_id=target_id,
                        target_name=target_name,
                        magnitude=spec.get("magnitude", 0.4),
                        direction=spec.get("direction", "actor_to_target"),
                        tool_name=tool_def.name,
                        tool_args={"action_description": action_description},
                        platform=platform,
                    )
                )

        return result

    tool_fn.__name__ = tool_def.name
    tool_fn.__qualname__ = tool_def.name
    tool_fn.__doc__ = (
        f"{tool_def.description}\n\n"
        f"Args:\n"
        f"    action_description (str): {tool_def.param_description}\n\n"
        f"Returns:\n"
        f"    str: A description of the action taken."
    )
    tool_fn.__annotations__ = {"action_description": str, "return": str}
    return tool_fn


