# Tool Registry — assembles everything
# ---------------------------------------------------------------------------


class ToolRegistry:
    """Assembles and caches tools for a simulation run.

    Usage:
        registry = ToolRegistry(config, simulation_requirement)
        tools_for_agent = registry.get_tools_for_agent(agent_id)
    """

    def __init__(
        self,
        simulation_config: dict[str, Any],
        simulation_requirement: str = "",
        enable_tools: bool = True,
    ):
        self._config = simulation_config
        self._requirement = simulation_requirement
        self._enabled = enable_tools
        self._scenario_tools: list[ScenarioToolDef] = []
        self._scenario_fns: list = []
        self._role_map: dict[int, str] = {}
        self._built = False

    def build(self, progress_callback=None):
        """Generate scenario tools and assign roles. Call once before simulation starts.

        If agent_configs already contain a 'tool_role' field (set by the
        config generator), those roles are reused instead of making a
        second LLM call.
        """
        if not self._enabled or self._built:
            return

        agent_configs = self._config.get("agent_configs", [])
        entity_types = list({ac.get("entity_type", "") for ac in agent_configs if ac.get("entity_type")})

        if progress_callback:
            progress_callback("Generating scenario-specific tools...")

        self._scenario_tools = generate_scenario_tool_definitions(self._requirement, entity_types)
        self._scenario_fns = [_make_scenario_tool_function(td) for td in self._scenario_tools]

        if progress_callback:
            progress_callback("Assigning tool roles to agents...")

        pre_assigned = {
            ac["agent_id"]: ac["tool_role"] for ac in agent_configs if ac.get("tool_role") and ac["tool_role"] != "none"
        }
        if pre_assigned:
            self._role_map = pre_assigned
            logger.info(f"Reusing {len(pre_assigned)} pre-assigned tool roles from config")
        else:
            self._role_map = assign_tool_roles(agent_configs, self._requirement)

        self._built = True
        logger.info(
            f"ToolRegistry built: {len(self._scenario_tools)} scenario tools, {len(self._role_map)} role assignments"
        )

    @property
    def scenario_tool_names(self) -> list[str]:
        return [t.name for t in self._scenario_tools]

    @property
    def role_map(self) -> dict[int, str]:
        return dict(self._role_map)

    @staticmethod
    def _bind_context(fn, agent_id: int, platform: str = ""):
        """Wrap a tool function so _current_agent_id and _current_platform
        are set when it executes.

        Preserves __name__, __doc__, __annotations__, and critically
        __signature__ so CAMEL's FunctionTool can introspect the wrapper
        exactly as it would the original function.
        """

        def wrapper(*args, **kwargs):
            id_token = _current_agent_id.set(agent_id)
            plat_token = _current_platform.set(platform)
            try:
                return fn(*args, **kwargs)
            finally:
                _current_platform.reset(plat_token)
                _current_agent_id.reset(id_token)

        wrapper.__name__ = fn.__name__
        wrapper.__qualname__ = fn.__qualname__
        wrapper.__doc__ = fn.__doc__
        wrapper.__module__ = getattr(fn, "__module__", __name__)
        wrapper.__annotations__ = getattr(fn, "__annotations__", {})
        wrapper.__signature__ = inspect.signature(fn)
        return wrapper

    def get_tools_for_agent(self, agent_id: int, platform: str = "") -> list | None:
        """Return list of FunctionTool instances for an agent, or None if no tools."""
        if not self._enabled or not self._built:
            return None

        role = self._role_map.get(agent_id, "none")
        if role == "none":
            return None

        try:
            from camel.toolkits import FunctionTool
        except ImportError:
            logger.error("camel.toolkits not available — cannot assign tools")
            return None

        def bind(fn):
            return self._bind_context(fn, agent_id, platform)

        tools = []

        if role == "leader":
            tools.append(FunctionTool(bind(web_search)))
            tools.extend(FunctionTool(bind(fn)) for fn in self._scenario_fns)
        elif role == "diplomat":
            tools.append(FunctionTool(bind(web_search)))
            tools.append(FunctionTool(bind(lookup_news)))
            tools.extend(FunctionTool(bind(fn)) for fn in self._scenario_fns)
        elif role == "analyst":
            tools.append(FunctionTool(bind(web_search)))
            tools.append(FunctionTool(bind(lookup_news)))
            tools.append(FunctionTool(bind(lookup_financial_data)))
        elif role == "operative":
            tools.append(FunctionTool(bind(web_search)))
            tools.extend(FunctionTool(bind(fn)) for fn in self._scenario_fns)
        elif role == "observer":
            tools.append(FunctionTool(bind(web_search)))

        return tools if tools else None

    def get_max_iterations(self, agent_id: int) -> int:
        """Return max LLM iterations per step for an agent (controls tool call depth)."""
        role = self._role_map.get(agent_id, "none")
        if role in ("leader", "diplomat"):
            return 3
        if role in ("analyst", "operative"):
            return 2
        return 1

    def to_dict(self) -> dict[str, Any]:
        """Serialize registry state for logging/config storage."""
        return {
            "enabled": self._enabled,
            "scenario_tools": [
                {"name": t.name, "description": t.description, "effects": t.effects} for t in self._scenario_tools
            ],
            "role_assignments": {str(k): v for k, v in self._role_map.items()},
        }
