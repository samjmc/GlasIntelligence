"""
Simulation Agent Tool Registry

Provides tool-use capabilities for simulation agents via OASIS's native
SocialAgent(tools=...) parameter. Handles:
- Universal tools (web search, news lookup)
- Scenario-specific tools generated by LLM from the simulation requirement
- Role-based tool assignment per agent
"""

import contextvars
import inspect
import json
import os
import re
import threading
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from openai import OpenAI

from ..config import Config
from ..utils.logger import get_logger

logger = get_logger("glas.simulation_tools")

MAX_TOOL_OUTPUT_CHARS = 500


# ---------------------------------------------------------------------------
# Tool-call side-channel logger
# ---------------------------------------------------------------------------
# OASIS only records final social actions in its trace table. Tool calls
# happen inside CAMEL's agent loop and are invisible to the DB.  This logger
# captures every tool invocation so the action stream can include them.


class ToolCallLogger:
    """Thread-safe side-channel logger for tool invocations.

    Writes tool calls to a JSONL file and supports offset-based reads so each
    consumer (e.g. per-platform simulation loop) only sees new entries.
    """

    _instance_lock = threading.Lock()
    _instances: dict[str, "ToolCallLogger"] = {}

    def __init__(self, log_path: str):
        self._path = log_path
        self._lock = threading.Lock()
        self._readers: dict[str, int] = {}

    @classmethod
    def get_or_create(cls, simulation_dir: str) -> "ToolCallLogger":
        with cls._instance_lock:
            if simulation_dir not in cls._instances:
                path = os.path.join(simulation_dir, "tool_calls.jsonl")
                cls._instances[simulation_dir] = cls(path)
            return cls._instances[simulation_dir]

    @classmethod
    def set_active(cls, simulation_dir: str):
        """Set the active simulation dir so tool functions can find it."""
        cls._active_dir = simulation_dir

    @classmethod
    def get_active(cls) -> "ToolCallLogger | None":
        d = getattr(cls, "_active_dir", None)
        if d is None:
            return None
        return cls._instances.get(d)

    @classmethod
    def clear_instances(cls):
        """Clear cached instances (call between simulation runs)."""
        with cls._instance_lock:
            cls._instances.clear()
            cls._active_dir = None

    def log(self, agent_id: int, tool_name: str, args: dict, result: str, platform: str = ""):
        entry = {
            "timestamp": datetime.now().isoformat(),
            "agent_id": agent_id,
            "tool_name": tool_name,
            "tool_args": args,
            "tool_result": result[:MAX_TOOL_OUTPUT_CHARS],
            "platform": platform,
        }
        with self._lock, open(self._path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    def fetch_new(self, reader_id: str = "default") -> list[dict]:
        """Return tool calls logged since this reader's last fetch.

        Each reader_id maintains its own offset, so Twitter and Reddit
        simulation loops can independently consume the same log file
        without stealing each other's entries.
        """
        entries = []
        with self._lock:
            if not os.path.exists(self._path):
                return entries
            offset = self._readers.get(reader_id, 0)
            with open(self._path, encoding="utf-8") as f:
                f.seek(offset)
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            entries.append(json.loads(line))
                        except json.JSONDecodeError:
                            pass
                self._readers[reader_id] = f.tell()
        return entries


# Tracks which agent/platform is currently executing a tool call (set by per-agent wrappers)
_current_agent_id: contextvars.ContextVar[int] = contextvars.ContextVar("_current_agent_id", default=-1)
_current_platform: contextvars.ContextVar[str] = contextvars.ContextVar("_current_platform", default="")


# ---------------------------------------------------------------------------
# Universal tool functions
# ---------------------------------------------------------------------------


def _log_tool_call(tool_name: str, args: dict, result: str):
    """Log a tool invocation to the side-channel if a logger is active."""
    tcl = ToolCallLogger.get_active()
    if tcl is not None:
        tcl.log(
            agent_id=_current_agent_id.get(),
            tool_name=tool_name,
            args=args,
            result=result,
            platform=_current_platform.get(),
        )


_search_toolkit_cache = None


def _ddg_search(query: str, max_results: int = 3) -> str:
    """Run a DuckDuckGo text search, trying CAMEL toolkit first, then direct."""
    global _search_toolkit_cache
    try:
        if _search_toolkit_cache is None:
            from camel.toolkits import SearchToolkit

            _search_toolkit_cache = SearchToolkit()
        raw = _search_toolkit_cache.search_duckduckgo(query=query, max_results=max_results)
        return str(raw)[:MAX_TOOL_OUTPUT_CHARS] if raw else ""
    except Exception:
        pass
    try:
        from duckduckgo_search import DDGS

        with DDGS() as ddgs:
            results = list(ddgs.text(query, max_results=max_results))
        if results:
            lines = [f"- {r.get('title', '')}: {r.get('body', '')}" for r in results]
            return "\n".join(lines)[:MAX_TOOL_OUTPUT_CHARS]
    except Exception:
        pass
    return ""


def web_search(query: str) -> str:
    """Search the web using DuckDuckGo and return a concise summary of results.

    Use this tool when you need current facts, news, or data to inform your
    social media posts or decisions.

    Args:
        query (str): The search query string.

    Returns:
        str: A summary of the top search results (max 500 chars).
    """
    try:
        result = _ddg_search(query) or "No results found."
        _log_tool_call("web_search", {"query": query}, result)
        return result
    except Exception as e:
        logger.warning(f"web_search failed for '{query}': {e}")
        return f"Search unavailable: {e}"


def lookup_news(topic: str) -> str:
    """Look up recent news articles about a topic using DuckDuckGo news search.

    Use this tool when you need the latest news coverage on a specific topic
    to reference or react to in your posts.

    Args:
        topic (str): The news topic to search for.

    Returns:
        str: A summary of recent news articles (max 500 chars).
    """
    try:
        result = _ddg_search(f"{topic} latest news") or "No news found."
        _log_tool_call("lookup_news", {"topic": topic}, result)
        return result
    except Exception as e:
        logger.warning(f"lookup_news failed for '{topic}': {e}")
        return f"News lookup unavailable: {e}"


def lookup_financial_data(query: str) -> str:
    """Look up financial or economic data related to a query.

    Use this tool when you need market data, economic indicators, or
    financial information to inform your analysis or posts.

    Args:
        query (str): The financial topic or instrument to look up (e.g.
            'oil prices', 'US GDP growth', 'AAPL stock').

    Returns:
        str: A summary of relevant financial data (max 500 chars).
    """
    try:
        result = _ddg_search(f"{query} financial data market") or "No financial data found."
        _log_tool_call("lookup_financial_data", {"query": query}, result)
        return result
    except Exception as e:
        logger.warning(f"lookup_financial_data failed for '{query}': {e}")
        return f"Financial data unavailable: {e}"


